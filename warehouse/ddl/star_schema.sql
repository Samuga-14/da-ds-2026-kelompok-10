-- Contract DDL for the TobaKost Star Schema Data Warehouse (928-row Survey_Kos.csv -> 923 fact rows).
-- Synchronized across data/tobakost_survey_warehouse.db and data/tobakost_warehouse.db.

CREATE TABLE dim_lokasi (
    id_lokasi TEXT PRIMARY KEY,
    kecamatan TEXT NOT NULL,
    desa_kelurahan TEXT NOT NULL,
    nama_kost TEXT,
    tujuan_utama TEXT,
    nama_tempat_krusial TEXT,
    area_tempat_makan TEXT
);

CREATE TABLE dim_spesifikasi_kamar (
    id_spesifikasi TEXT PRIMARY KEY,
    luas_kamar_m2 REAL,
    jumlah_lantai REAL,
    kategori_lantai TEXT,
    tipe_kamar_mandi TEXT,
    kelengkapan_kamar_mandi TEXT,
    ac INTEGER,
    ac_non_ac TEXT,
    fasilitas TEXT,
    fasilitas_kamar_detail TEXT,
    ada_dipan INTEGER,
    ada_kasur INTEGER,
    ada_lemari INTEGER,
    ada_meja_belajar INTEGER,
    ada_tv INTEGER,
    ada_cermin INTEGER,
    ada_kulkas_pribadi INTEGER,
    kloset_duduk INTEGER,
    kloset_jongkok INTEGER,
    ada_shower INTEGER,
    ada_water_heater INTEGER,
    jenis_kos TEXT NOT NULL CHECK (jenis_kos IN ('ekonomi', 'eksekutif'))
);

CREATE TABLE dim_fasilitas_aturan (
    id_aturan TEXT PRIMARY KEY,
    kategori_penghuni TEXT,
    status_penyewa TEXT,
    sumber_air TEXT,
    sumber_air_utama TEXT,
    wifi TEXT,
    wifi_non_wifi TEXT,
    fasilitas_dapur TEXT,
    fasilitas_dapur_kulkas TEXT,
    dapur TEXT,
    fasilitas_cuci_jemur TEXT,
    lahan_parkir TEXT,
    keamanan_kos TEXT,
    aturan_jam_malam TEXT,
    aturan_jam_malam_masuk TEXT,
    kapasitas_kamar TEXT,
    skema_listrik TEXT,
    skema_biaya_listrik TEXT,
    listrik_termasuk INTEGER
);

CREATE TABLE dim_kontrak_sewa (
    id_kontrak TEXT PRIMARY KEY,
    periode_sewa TEXT,
    sewa_tahunan INTEGER,
    sewa_tahunan_bulanan TEXT,
    is_tahunan INTEGER,
    tahun_mulai_sewa TEXT,
    faktor_konversi_bulanan INTEGER
);

CREATE TABLE fact_sewa_kos (
    id_kost TEXT PRIMARY KEY,
    kode_unit_kos TEXT,
    nama_kost TEXT,
    id_lokasi TEXT NOT NULL REFERENCES dim_lokasi(id_lokasi),
    id_spesifikasi TEXT NOT NULL REFERENCES dim_spesifikasi_kamar(id_spesifikasi),
    id_aturan TEXT NOT NULL REFERENCES dim_fasilitas_aturan(id_aturan),
    id_kontrak TEXT NOT NULL REFERENCES dim_kontrak_sewa(id_kontrak),
    harga_sewa REAL,
    harga_bulanan_norm REAL,
    status_harga TEXT,
    harga_masih_berlaku INTEGER,
    kos_aktif INTEGER,
    jarak_kampus_sekolah_tempatkerja_m REAL,
    jarak_pasar_minimarket_m REAL,
    jarak_fasilitas_kesehatan_m REAL,
    jarak_tempat_ibadah_m REAL,
    jarak_laundry_m INTEGER,
    jarak_pusat_kota_m INTEGER,
    jarak_jalan_raya_m REAL,
    jarak_ke_kampus_kantor_sekolah_terdekat_km REAL,
    jarak_ke_pasar_km REAL,
    jarak_krusial_km REAL,
    jarak_ibadah_m INTEGER,
    jarak_ke_jalan_raya_m INTEGER,
    klasifikasi_jarak_kampus_sekolah_tempatkerja TEXT,
    klasifikasi_jarak_pasar_minimarket TEXT,
    klasifikasi_jarak_fasilitas_kesehatan TEXT,
    klasifikasi_jarak_tempat_ibadah TEXT,
    klasifikasi_jarak_laundry TEXT,
    klasifikasi_jarak_pusat_kota TEXT,
    klasifikasi_jarak_jalan_raya TEXT,
    area_tempat_makan TEXT,
    biaya_tambahan_rp REAL,
    skor_kelengkapan_fasilitas REAL,
    indeks_aksesibilitas_lokasi REAL,
    latitude REAL,
    longitude REAL,
    source_url TEXT,
    exact_duplicate INTEGER,
    duplicate_logis INTEGER,
    price_anomaly_iqr INTEGER,
    accepted_for_analysis INTEGER,
    model_ready INTEGER
);
